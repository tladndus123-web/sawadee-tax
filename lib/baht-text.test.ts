import { describe, expect, it } from "vitest";
import { bahtText, cleanWords, thaiInt } from "./baht-text";

describe("bahtText", () => {
  it.each([
    [64200, "หกหมื่นสี่พันสองร้อยบาทถ้วน"],
    [21, "ยี่สิบเอ็ดบาทถ้วน"],
    [1000001, "หนึ่งล้านเอ็ดบาทถ้วน"],
    [0.5, "ห้าสิบสตางค์"],
    [11.25, "สิบเอ็ดบาทยี่สิบห้าสตางค์"],
    // extra cases
    [0, "ศูนย์บาทถ้วน"],
    [1, "หนึ่งบาทถ้วน"],
    [10, "สิบบาทถ้วน"],
    [11, "สิบเอ็ดบาทถ้วน"],
    [101, "หนึ่งร้อยเอ็ดบาทถ้วน"],
    [4200, "สี่พันสองร้อยบาทถ้วน"],
    [1000000, "หนึ่งล้านบาทถ้วน"],
    [21000000, "ยี่สิบเอ็ดล้านบาทถ้วน"],
    [1234567.89, "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์"],
  ])("%s → %s", (n, words) => {
    expect(bahtText(n)).toBe(words);
  });

  it("thaiInt of 0 is empty", () => {
    expect(thaiInt(0)).toBe("");
  });

  it("cleanWords drops spaces and brackets", () => {
    expect(cleanWords("(หกหมื่นสี่พัน สองร้อยบาทถ้วน)")).toBe("หกหมื่นสี่พันสองร้อยบาทถ้วน");
    expect(cleanWords("（หนึ่งบาทถ้วน）")).toBe("หนึ่งบาทถ้วน");
  });
});
